CREATE TABLE IF NOT EXISTS member_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mobile VARCHAR(11) NOT NULL,
 password VARCHAR(100) NOT NULL, nickname VARCHAR(30) NOT NULL, avatar VARCHAR(1024), email VARCHAR(254),
 sex TINYINT, status TINYINT NOT NULL DEFAULT 0, register_ip VARCHAR(64), login_ip VARCHAR(64), login_date TIMESTAMP,
 creator VARCHAR(64) DEFAULT '', create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(64) DEFAULT '', update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted BOOLEAN DEFAULT FALSE,
 CONSTRAINT uk_member_user_mobile UNIQUE (mobile), CONSTRAINT chk_member_user_status CHECK (status IN (0,1)),
 CONSTRAINT chk_member_user_sex CHECK (sex IS NULL OR sex IN (0,1,2))
);
CREATE TABLE IF NOT EXISTS member_address (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, name VARCHAR(30) NOT NULL,
 mobile VARCHAR(11) NOT NULL, area_id INT NOT NULL, detail_address VARCHAR(255) NOT NULL,
 default_status BOOLEAN NOT NULL DEFAULT FALSE, default_marker TINYINT,
 creator VARCHAR(64) DEFAULT '', create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(64) DEFAULT '', update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, deleted BOOLEAN DEFAULT FALSE,
 CONSTRAINT uk_member_address_default UNIQUE (user_id, default_marker),
 CONSTRAINT fk_member_address_user FOREIGN KEY (user_id) REFERENCES member_user(id)
);
